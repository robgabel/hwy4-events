/**
 * Hand-curated content for town landing pages.
 *
 * Each entry is drafted by Claude Opus via `scripts/draft-town-content.ts`,
 * which pulls `docs/LOCAL-KNOWLEDGE-BASE.md` + `docs/PERSONAS.md` + the About
 * page voice as context, then reviewed and edited by Rob before commit.
 *
 * Voice rules (enforced by the draft script's system prompt):
 * - Reference real local businesses, owner names, and landmarks. No generic
 *   "explore the charming town" copy.
 * - Persona-targeted: each town speaks to at least one of Gary, Mia, Karen,
 *   Miguel, Jen by lived situation, not by name.
 * - No banned marketing phrases: "discover", "explore", "your gateway to",
 *   "nestled in the heart of", "charming", "hidden gem".
 * - Falsifiable specifics over vibes ("the post office closes at 4:30").
 * - No em dashes. SOUL.md voice rule. Use commas, periods, semicolons.
 *
 * To add a town: run `npx tsx scripts/draft-town-content.ts <slug>`, review
 * the printed draft, and paste it into this registry. Towns without an entry
 * here will 404 (intentional, we only ship pages with real content).
 */

import type { FaqEntry } from "@/lib/schema";

export interface TownContent {
  /** URL slug. Matches the dynamic route param. */
  slug: string;
  /** Canonical town name from CORRIDOR_TOWNS. */
  townName: string;
  /** <title> override. */
  metaTitle: string;
  /** Meta description. 150 to 160 chars. */
  metaDescription: string;
  /** Page H1. */
  h1: string;
  /** Single-line subhead beneath the H1. */
  subhead: string;
  /** Above-the-fold teaser. 1-2 sentences. Always visible. Highest AEO weight,
   * since snippet engines often quote the first ~1500 chars of a page. */
  introTeaser: string;
  /** Long-form intro paragraphs. 2 to 3 paragraphs, 300 to 500 words total,
   * drafted by Opus. Rendered inside a <details> behind a "Read more" toggle. */
  intro: string[];
  /** "If you're..." persona-targeted bullets (3 to 6 items). */
  personaNotes: string[];
  /** Falsifiable local facts: parking, hours, who's open in winter, etc. */
  worthKnowing: string[];
  /** Town-specific Q&A. 3 to 5 items. */
  faqs: FaqEntry[];
  /** YYYY-MM-DD. Surfaced as the page's "Last verified by Rob" stamp. */
  lastVerified: string;
  /**
   * Draft / pending verification. When true:
   * - page renders a visible "DRAFT" banner at the top
   * - metadata sets robots: noindex, nofollow
   * - sitemap.ts excludes the URL so Google doesn't crawl it
   * - lastVerified date is ignored in the byline (replaced with "Pending verification")
   * Set false (or omit) only after every fact on the page is sourced and confirmed.
   */
  draft?: boolean;
}

