export function getTownContent(slug: string): TownContent | null {
  return TOWN_CONTENT[slug] ?? null;
}

/** Every town that has a content entry. Used for generateStaticParams so
 * drafts pre-render and are reachable for review. */
export function getAllTownSlugs(): string[] {
  return Object.keys(TOWN_CONTENT);
}

/** Only towns with verified content. Used for sitemap.xml so drafts are
 * not advertised to search engines. */
export function getPublishedTownSlugs(): string[] {
  return Object.entries(TOWN_CONTENT)
    .filter(([, c]) => !c.draft)
    .map(([slug]) => slug);
}
